#' Is Probability Vector
#' @description A function used to check if a vector is a valid probability
#' vector (i.e., numeric and all values between 0 and 1). This is used in the
#' validation of capture and category probabilities for data generation.
#' @param vec a vector to check
#' @returns a boolean indicating whether the vector is a valid probability
#' vector
#'
#' @keywords internal
#' @export
is_probability_vector <- function(vec) {
    if (!is.vector(vec)) {
        return(FALSE)
    }
    if (!is.numeric(vec)) {
        warning("Input vector must be numeric.")
        return(FALSE)
    }
    if (any(vec < 0 | vec > 1)) {
        warning("All values in the input vector must be between 0 and 1.")
        return(FALSE)
    }
    return(TRUE)
}

#' Is Probability Scalar
#' @description A function used to check if a value is a valid probability
#' scalar (i.e., numeric, length 1, and between 0 and 1). This is used in the
#' validation of capture and category probabilities for data generation when
#' the user specifies a single probability to be applied across all captures or
#' categories.
#' @param value a value to check
#' @returns a boolean indicating whether the value is a valid probability scalar
#'
#' @keywords internal
#' @export
is_probability_scalar <- function(value) {
    if (!is.numeric(value) || length(value) != 1) {
        warning("Input must be a numeric scalar.")
        return(FALSE)
    }
    if (value < 0 || value > 1) {
        warning("Input value must be between 0 and 1.")
        return(FALSE)
    }
    return(TRUE)
}

#' Data generation tool. This creates a simulated dataset for testing various
#' Capture-Recapture models. The user is able to specify the number of
#' individuals, the number of captures, and optional numerical covariates
#' generated from per-covariate distribution settings. The returned value
#' represents the "raw" simulated data where each row is a single sample.
#' Frequency tables can also be generated by setting
#' \code{return_frequency_table} to \code{TRUE}, which will aggregate identical
#' rows and append a frequency column \code{N_ID}.
#'
#' @param n_individuals int: number of participants to simulate
#' @param n_captures int: number of binary capture columns to simulate
#' @param p_captures numeric vector: optional capture probabilities of length
#'   \code{n_captures}. Defaults to 0.5 for each capture column.
#' @param covariate_ranges data.frame: optional covariate specification table
#'   with columns \code{distribution}, \code{p1}, \code{p2}, and \code{dtype}.
#'   Each row defines one numerical covariate named \code{covariate_i}.
#'   Supported distributions are \code{uniform} and \code{normal}. For
#'   \code{uniform}, \code{p1 = low} and \code{p2 = high}. For \code{normal},
#'   \code{p1 = mean} and \code{p2 = standard deviation}.
#' @param return_frequency_table logical: when \code{TRUE}, aggregates identical
#'   rows and appends frequency column \code{N_ID}. Default is \code{FALSE}.
#'
#' @returns a tibble
#'
#' @export
create_data <- function(
    n_individuals,
    n_captures,
    p_captures = NULL,
    covariate_ranges = NULL,
    return_frequency_table = FALSE
) {
    validate_create_args(
        n_individuals = n_individuals,
        n_captures = n_captures,
        covariate_ranges = covariate_ranges,
        return_frequency_table = return_frequency_table
    )

    capture_probs <- normalize_p_captures(
        n_captures = n_captures,
        p_captures = p_captures
    )

    covariate_specs <- normalize_covariate_ranges(
        covariate_ranges = covariate_ranges
    )

    records <- build_individual_records(
        n_individuals = n_individuals,
        capture_probs = capture_probs,
        covariate_specs = covariate_specs
    )

    if (isTRUE(return_frequency_table)) {
        return(build_contingency_table(records))
    }

    return(records)
}

#' Apply Suppression to Frequency Table Data.
#' This function takes a frequency table dataset and applies suppression to the
#' frequency column.
#'
#' @param data data.frame: the frequency table dataset to apply suppression to
#' @param suppression_threshold int: the threshold at which to apply
#' suppression.
#' @param freq_col string: the name of the frequency column in the dataset.
#' Default is "N_ID".
#' @return a data.frame with suppression applied to the frequency column
#'
#' @importFrom dplyr mutate
#' @export
suppress_data <- function(data, suppression_threshold, freq_col = "N_ID") {
    if (!isTRUE(suppression_threshold > 0)) {
        return(data)
    }

    if (!freq_col %in% colnames(data)) {
        stop(
            "Frequency column N_ID not found in data. Cannot apply suppression."
        )
    }
    suppressed_data <- data |>
        dplyr::mutate(
            {{ freq_col }} := ifelse(
                {{ freq_col }} <= suppression_threshold,
                -1,
                {{ freq_col }}
            )
        )

    return(suppressed_data)
}

#' Get Captured Rows
#' @description Function to filter out rows where all capture columns are not 0.
#' This is used to identify all the captured rows in a dataset.
#'
#' @param data_table data.frame: Data frame containing either a frequency table
#' or individual records with capture columns.
#' @param capture character vector: names of capture columns
#' @returns tibble containing only rows where people are captured.
#'
#' @importFrom dplyr filter across
#' @importFrom tibble as_tibble
#' @export
extract_captured_data <- function(data_table, capture) {
    captured_rows <- tibble::as_tibble(data_table) |>
        dplyr::filter(rowSums(dplyr::across(capture)) != 0)
    return(captured_rows)
}

#' Get Uncaptured Rows
#' @description Function to filter out rows where all capture columns are 0.
#' This is used to identify all the uncaptured rows in a dataset, which is
#' necessary for extracting a ground truth value for simulation evaluation.
#'
#' @param data_table data.frame: Data frame containing either a frequency table
#' or individual records with capture columns.
#' @param capture character vector: names of capture columns
#' @returns tibble containing only rows where people are uncaptured.
#'
#' @importFrom dplyr filter across
#' @importFrom tibble as_tibble
#' @export
extract_uncaptured_data <- function(data_table, capture) {
    uncaptured_rows <- tibble::as_tibble(data_table) |>
        dplyr::filter(rowSums(dplyr::across(capture)) == 0)
    return(uncaptured_rows)
}

#' A function used to check if a column in a data frame is binary
#' (i.e., contains only 0s and 1s).
#'
#' @param column a vector representing a column in a data frame
#' @returns a boolean indicating whether the column is binary
#'
#' @keywords internal
#' @export
is_column_binary <- function(column) {
    unique_values <- unique(column)
    return(length(unique_values) == 2 && all(unique_values %in% c(0, 1)))
}

#' A function used to check if the provided data is a frequency table. This is
#' necessary as the CRC estimation functions require a frequency table as input.
#'
#' @param data a data frame
#' @param frequency_column a string specifying the name of the frequency column
#' in the data frame
#' @returns a boolean indicating whether the data frame is a frequency table
#' (i.e., contains the specified frequency column and that column is numeric)
#'
#' @keywords internal
#' @export
is_frequency_table <- function(data, frequency_column) {
    if (
        frequency_column %in%
            names(data) &&
            is.numeric(data[[frequency_column]])
    ) {
        return(TRUE)
    }
    return(FALSE)
}

#' A function used to convert all integer columns to numeric. This is necessary
#' as the drpop package requires all data columns to be numerics.
#' This is a temporary workaround until we can implement our own TMLE estimation
#' function that can handle integer columns.
#'
#' @param df a data frame
#' @returns a data frame with all integer columns converted to numeric
#'
#' @importFrom dplyr mutate across where
#' @keywords internal
#' @export
all_int_cols_to_numeric <- function(df) {
    return(mutate(df, across(where(is.integer), as.numeric)))
}

#' Build Individual Simulation Records. This builds all the individual records
#' for a simulated dataset. Each record produced by this function represents
#' one individual and contains the capture indicators and simulated numerical
#' covariate indicators. This function is traditionally wrapped by
#' \code{create_data} but
#' exposed for users who want more granular control over building the simulation
#' data. Importantly, the capture_probs and covariate_specs are not validated so
#' errors may not be as descriptive.
#'
#' @param n_individuals int: number of participants to simulate
#' @param capture_probs numeric vector: capture probabilities of length equal to
#'  the number of capture columns
#' @param covariate_specs data.frame: covariate specification table with one row
#' per covariate and columns \code{distribution}, \code{p1}, \code{p2}, and
#' \code{dtype}.
#' @returns a tibble where each row is an individual record
#'
#' @keywords internal
#' @export
build_individual_records <- function(
    n_individuals,
    capture_probs,
    covariate_specs
) {
    records <- purrr::map(
        seq_len(n_individuals),
        create_individual_record,
        capture_probs = capture_probs,
        covariate_specs = covariate_specs
    ) |>
        purrr::list_rbind()

    return(records)
}

#' Aggregate Records into a Contingency Table. This function takes the row level
#' records produced by \code{build_individual_records} and aggregates identical
#' rows while appending a frequency column \code{N_ID}.
#'
#' @param records tibble: raw data where each row is an individual record with
#' capture and covariate category columns.
#' @return a contingency table tibble where identical rows in the input are
#' aggregated and a frequency column \code{N_ID} is appended.
#'
#' @importFrom dplyr count across everything
#' @keywords internal
#' @export
build_contingency_table <- function(records) {
    return(count(records, across(everything()), name = "N_ID"))
}

#' Validate Inputs for create_data. This checks that all inputs are of the
#' correct type and value range. If any checks fail, an error is thrown.
#' Exclusively used within \code{create_data}.
#'
#' As this is a validation function with a lot of if checks, we ignore
#' cyclocomp_linter.
#'
#' @keywords internal
#' @noRd
# nolint start: cyclocomp_linter
validate_create_args <- function(
    n_individuals,
    n_captures,
    covariate_ranges,
    return_frequency_table
) {
    if (!is.numeric(n_individuals) || length(n_individuals) != 1) {
        stop("n_individuals must be a numeric scalar")
    }
    if (!is.numeric(n_captures) || length(n_captures) != 1) {
        stop("n_captures must be a numeric scalar")
    }
    if (n_individuals < 1 || n_individuals %% 1 != 0) {
        stop("n_individuals must be a positive integer")
    }
    if (n_captures < 1 || n_captures %% 1 != 0) {
        stop("n_captures must be a positive integer")
    }
    if (!is.null(covariate_ranges) && !is.data.frame(covariate_ranges)) {
        stop("covariate_ranges must be a data.frame or NULL")
    }
    if (
        !is.logical(return_frequency_table) ||
            length(return_frequency_table) != 1
    ) {
        stop("return_frequency_table must be a logical scalar")
    }

    return(invisible(NULL))
}
# nolint end: cyclocomp_linter

#' Normalize Capture Probabilities. This first checks that the capture
#' probabilities are specified and if not returns the default
#' (0.5 for each capture column). If probabilities are specified, this checks
#' that they are numeric, of the correct length, and between 0 and 1. If any
#' checks fail, an error is thrown. This is an internal function used within
#' \code{create_data}.
#'
#' @keywords internal
#' @noRd
normalize_p_captures <- function(n_captures, p_captures) {
    if (is.null(p_captures)) {
        return(rep(0.5, n_captures))
    }

    if (!is.numeric(p_captures)) {
        stop("p_captures must be a numeric vector")
    }
    if (length(p_captures) != n_captures) {
        stop("Length of p_captures must equal n_captures")
    }
    if (any(p_captures < 0 | p_captures > 1)) {
        stop("All p_captures values must be between 0 and 1")
    }

    return(as.numeric(p_captures))
}

#' Normalize Covariate Specifications. This validates and standardizes
#' \code{covariate_ranges} for use in \code{create_data}. The expected columns
#' are \code{distribution}, \code{p1}, \code{p2}, and \code{dtype}, where each
#' row defines one generated covariate.
#'
#' As this is a validation function with a lot of if checks, we ignore
#' cyclocomp_linter.
#'
#' @keywords internal
#' @noRd
# nolint start: cyclocomp_linter
normalize_covariate_ranges <- function(covariate_ranges) {
    if (is.null(covariate_ranges)) {
        return(data.frame(
            distribution = character(0),
            p1 = numeric(0),
            p2 = numeric(0),
            dtype = character(0)
        ))
    }

    required_columns <- c("distribution", "p1", "p2", "dtype")
    if (!all(required_columns %in% names(covariate_ranges))) {
        stop(
            paste(
                "covariate_ranges must contain columns:",
                "distribution, p1, p2, dtype"
            )
        )
    }

    covariate_specs <- covariate_ranges[, required_columns, drop = FALSE]

    if (nrow(covariate_specs) == 0) {
        return(covariate_specs)
    }

    covariate_specs[["distribution"]] <- tolower(as.character(
        covariate_specs[["distribution"]]
    ))
    covariate_specs[["dtype"]] <- tolower(as.character(covariate_specs[[
        "dtype"
    ]]))

    invalid_distributions <- setdiff(
        unique(covariate_specs[["distribution"]]),
        c("uniform", "normal")
    )
    if (length(invalid_distributions) > 0) {
        stop("distribution must be one of: uniform, normal")
    }

    invalid_dtypes <- setdiff(
        unique(covariate_specs[["dtype"]]),
        c("numeric", "integer")
    )
    if (length(invalid_dtypes) > 0) {
        stop("dtype must be one of: numeric, integer")
    }

    if (
        !is.numeric(covariate_specs[["p1"]]) ||
            !is.numeric(covariate_specs[["p2"]])
    ) {
        stop("p1 and p2 must be numeric")
    }
    if (any(is.na(covariate_specs[["p1"]]) | is.na(covariate_specs[["p2"]]))) {
        stop("p1 and p2 cannot contain NA values")
    }

    uniform_rows <- covariate_specs[["distribution"]] == "uniform"
    if (
        any(
            covariate_specs[["p1"]][uniform_rows] >
                covariate_specs[["p2"]][uniform_rows]
        )
    ) {
        stop("For uniform, p1 (low) must be <= p2 (high)")
    }

    normal_rows <- covariate_specs[["distribution"]] == "normal"
    if (any(covariate_specs[["p2"]][normal_rows] <= 0)) {
        stop("For normal, p2 (standard deviation) must be > 0")
    }

    return(covariate_specs)
}
# nolint end: cyclocomp_linter

#' Create One Individual Simulation Record. This simulates a single record of
#' data for one individual, including the capture indicators and numerical
#' covariates. The return type is a tibble row.
#' This is an internal function used within \code{build_individual_records}.
#'
#' @keywords internal
#' @noRd
create_individual_record <- function(index, capture_probs, covariate_specs) {
    invisible(index)
    capture_values <- create_capture(capture_probs)
    covariate_values <- sample_covariate_values(covariate_specs)

    record_values <- as.list(capture_values)
    record_values <- c(record_values, covariate_values)

    return(tibble::as_tibble_row(record_values))
}

#' A function to generate binomial flips along the probability specified
#'
#' @param prob numeric vector: probabilities respective to each \code{n}
#'
#' @importFrom stats rbinom
#' @keywords internal
#' @noRd
create_capture <- function(prob) {
    n <- length(prob)
    out <- as.integer(stats::rbinom(n = n, size = 1, prob = prob))
    names(out) <- paste0("capture_", 1:n)
    return(out)
}

#' Sample numerical covariate values for one individual
#'
#' @importFrom stats runif rnorm
#'
#' @keywords internal
#' @noRd
sample_covariate_values <- function(covariate_specs) {
    n <- nrow(covariate_specs)
    if (n == 0) {
        return(list())
    }

    values <- vector("list", n)
    for (i in seq_len(n)) {
        values[[i]] <- sample_covariate_value(covariate_specs[
            i,
            ,
            drop = FALSE
        ])
    }
    names(values) <- paste0("covariate_", seq_len(n))

    return(values)
}

#' Sample one numerical covariate value from a specification row
#'
#' @importFrom stats runif rnorm
#' @keywords internal
#' @noRd
sample_covariate_value <- function(covariate_spec_row) {
    distribution <- covariate_spec_row[["distribution"]][[1]]
    p1 <- covariate_spec_row[["p1"]][[1]]
    p2 <- covariate_spec_row[["p2"]][[1]]
    dtype <- covariate_spec_row[["dtype"]][[1]]

    if (distribution == "uniform") {
        value <- stats::runif(n = 1, min = p1, max = p2)
    } else if (distribution == "normal") {
        value <- stats::rnorm(n = 1, mean = p1, sd = p2)
    } else {
        stop("Unsupported distribution in covariate specification")
    }

    if (dtype == "integer") {
        return(as.integer(round(value)))
    }

    out <- as.numeric(value)
    return(out)
}
